def find_section_indices(document) -> tuple[int, int]:
    start = None
    end = None
    for idx in range(1, document.Paragraphs.Count + 1):
        text = document.Paragraphs(idx).Range.Text.strip()
        if text.startswith("3.2 "):
            start = idx
        elif start is not None and text.startswith("3.3 "):
            end = idx
            break
    if start is None or end is None:
        raise RuntimeError("Could not locate Section 3.2 and Section 3.3 boundaries.")
    return start, end


def type_paragraph(selection, text: str, heading_level: int | None = None) -> None:
    selection.Font.Name = "Times New Roman"
    selection.Font.Size = 11
    selection.Font.Bold = bool(heading_level)
    selection.TypeText(text)
    selection.TypeParagraph()
    selection.Font.Bold = False


def type_equation(word, document, selection, equation: str) -> None:
    selection.Font.Name = "Cambria Math"
    selection.Font.Size = 11
    start = selection.Start
    selection.TypeText(equation)
    end = selection.End
    rng = document.Range(start, end)
    omath = document.OMaths.Add(rng)
    omath.BuildUp()
    selection.SetRange(omath.Range.End, omath.Range.End)
    selection.TypeParagraph()
    selection.Font.Name = "Times New Roman"


def main() -> None:
    if not DOC_PATH.exists():
        raise FileNotFoundError(DOC_PATH)
    if not BACKUP_PATH.exists():
        shutil.copy2(DOC_PATH, BACKUP_PATH)

    word = win32.DispatchEx("Word.Application")
    word.Visible = False
    word.DisplayAlerts = 0
    document = word.Documents.Open(str(DOC_PATH))
    saved = False

    try:
        start_idx, end_idx = find_section_indices(document)
        start = document.Paragraphs(start_idx).Range.Start
        end = document.Paragraphs(end_idx).Range.Start
        document.Range(start, end).Delete()

        selection = word.Selection
        selection.SetRange(start, start)

        for kind, content in SECTION_ITEMS:
            if kind == "heading":
                type_paragraph(selection, content, heading_level=2)
            elif kind == "paragraph":
                type_paragraph(selection, content)
            elif kind == "equation":
                type_equation(word, document, selection, content)
            else:
                raise ValueError(f"Unknown item kind: {kind}")

        document.Save()
        saved = True
    finally:
        document.Close(SaveChanges=saved)
        word.Quit()

    print(f"Updated: {DOC_PATH}")
    print(f"Backup: {BACKUP_PATH}")


if __name__ == "__main__":
    main()
